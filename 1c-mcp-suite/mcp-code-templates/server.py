# ─── Поиск ────────────────────────────────────────────────────────────────

def _search_templates(query: str, tags: list[str] = None, limit: int = 10) -> list[dict]:
    q = query.lower()
    scored = []
    for tpl in TEMPLATES:
        score = 0
        title = tpl.get("title", "").lower()
        desc = tpl.get("description", "").lower()
        tpl_tags = [t.lower() for t in tpl.get("tags", [])]
        code = tpl.get("code", "").lower()

        # По тегам
        if tags:
            for t in tags:
                if t.lower() in tpl_tags:
                    score += 20

        # По заголовку
        if q in title:
            score += 15
        # По описанию
        if q in desc:
            score += 10
        # По тегам
        for t in tpl_tags:
            if q in t:
                score += 8
        # По коду
        if q in code:
            score += 3

        if score > 0:
            scored.append((score, tpl))

    scored.sort(key=lambda x: -x[0])
    return [t for _, t in scored[:limit]]


# ─── MCP инструменты ─────────────────────────────────────────────────────

@mcp.tool()
def templates_search(query: str, limit: int = 5) -> str:
    """
    Поиск шаблонов и примеров кода 1С.

    Параметры:
      query — строка поиска (например, "запрос", "транзакция", "http", "json", "проведение")
      limit — максимум результатов
    """
    results = _search_templates(query, limit=limit)
    if not results:
        return json.dumps({"message": f"По запросу '{query}' шаблоны не найдены"}, ensure_ascii=False)
    return json.dumps(results, ensure_ascii=False, indent=2)


@mcp.tool()
def templates_by_tags(tags: str, limit: int = 10) -> str:
    """
    Поиск шаблонов по тегам (через запятую).

    Параметр tags — теги через запятую (например, "запрос, соединение" или "http, json").
    """
    tag_list = [t.strip() for t in tags.split(",") if t.strip()]
    results = _search_templates(" ".join(tag_list), tags=tag_list, limit=limit)
    if not results:
        return json.dumps({"message": f"По тегам '{tags}' шаблоны не найдены"}, ensure_ascii=False)
    return json.dumps(results, ensure_ascii=False, indent=2)


@mcp.tool()
def templates_list_tags() -> str:
    """Список всех доступных тегов шаблонов."""
    all_tags = defaultdict(int)
    for tpl in TEMPLATES:
        for t in tpl.get("tags", []):
            all_tags[t] += 1
    sorted_tags = sorted(all_tags.items(), key=lambda x: -x[1])
    return json.dumps([{"tag": t, "count": c} for t, c in sorted_tags], ensure_ascii=False, indent=2)


@mcp.tool()
def templates_count() -> str:
    """Общее количество шаблонов в базе."""
    return json.dumps({"total": len(TEMPLATES)}, ensure_ascii=False)


