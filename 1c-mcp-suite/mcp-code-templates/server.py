def _st_skip_ws(text: str, pos: int) -> int:
    while pos < len(text) and text[pos] in ' \t\r\n':
        pos += 1
    return pos


def _st_read_int(text: str, pos: int) -> tuple[int, int]:
    start = pos
    while pos < len(text) and text[pos].isdigit():
        pos += 1
    if pos > start:
        return int(text[start:pos]), pos
    return 0, pos


def _st_read_string(text: str, pos: int) -> tuple[str, int]:
    """Читает строку в кавычках, обрабатывая «""» как экранированную кавычку."""
    if pos >= len(text) or text[pos] != '"':
        return "", pos
    pos += 1
    chars = []
    while pos < len(text):
        if text[pos] == '"':
            if pos + 1 < len(text) and text[pos + 1] == '"':
                chars.append('"')
                pos += 2
            else:
                pos += 1
                break
        else:
            chars.append(text[pos])
            pos += 1
    return "".join(chars), pos


def _st_peek_is_header(text: str, pos: int) -> bool:
    """Проверяет, является ли следующий блок {...} заголовком (начинается с кавычки)."""
    p = _st_skip_ws(text, pos)
    if p >= len(text) or text[p] != '{':
        return False
    p += 1
    p = _st_skip_ws(text, p)
    return p < len(text) and text[p] == '"'


def _st_parse_node(text: str, pos: int, path: list[str], templates: list[dict]) -> int:
    """Рекурсивно парсит узел .st дерева."""
    pos = _st_skip_ws(text, pos)
    if pos >= len(text) or text[pos] != '{':
        return pos
    pos += 1
    pos = _st_skip_ws(text, pos)

    num_children, pos = _st_read_int(text, pos)
    pos = _st_skip_ws(text, pos)
    if pos < len(text) and text[pos] == ',':
        pos += 1
    pos = _st_skip_ws(text, pos)

    title = ""
    code = ""
    snippet = ""

    if _st_peek_is_header(text, pos):
        pos += 1
        pos = _st_skip_ws(text, pos)
        title, pos = _st_read_string(text, pos)
        pos = _st_skip_ws(text, pos)
        if pos < len(text) and text[pos] == ',': pos += 1
        pos = _st_skip_ws(text, pos)
        _, pos = _st_read_int(text, pos)   # is_group
        pos = _st_skip_ws(text, pos)
        if pos < len(text) and text[pos] == ',': pos += 1
        pos = _st_skip_ws(text, pos)
        _, pos = _st_read_int(text, pos)   # flag
        pos = _st_skip_ws(text, pos)
        if pos < len(text) and text[pos] == ',': pos += 1
        pos = _st_skip_ws(text, pos)
        snippet, pos = _st_read_string(text, pos)
        pos = _st_skip_ws(text, pos)
        if pos < len(text) and text[pos] == ',': pos += 1
        pos = _st_skip_ws(text, pos)
        code, pos = _st_read_string(text, pos)
        pos = _st_skip_ws(text, pos)
        if pos < len(text) and text[pos] == '}':
            pos += 1
        pos = _st_skip_ws(text, pos)

    if num_children == 0:
        if code.strip():
            tags = [p for p in path if p] or ["пользовательский"]
            templates.append({
                "title": title,
                "description": title + (f" (сниппет: {snippet})" if snippet else ""),
                "tags": tags,
                "code": code,
            })
    else:
        current_path = path + [title] if title else path
        if pos < len(text) and text[pos] == ',':
            pos += 1
        for _ in range(num_children):
            pos = _st_skip_ws(text, pos)
            if pos < len(text) and text[pos] == ',':
                pos += 1
            pos = _st_parse_node(text, pos, current_path, templates)
            pos = _st_skip_ws(text, pos)
            if pos < len(text) and text[pos] == ',':
                pos += 1

    pos = _st_skip_ws(text, pos)
    if pos < len(text) and text[pos] == '}':
        pos += 1
    return pos


def _parse_st_file(filepath: str) -> list[dict]:
    """Парсит .st файл шаблонов 1С и возвращает список шаблонов."""
    for enc in ("utf-8-sig", "utf-8", "cp1251"):
        try:
            with open(filepath, "r", encoding=enc) as f:
                content = f.read()
            break
        except (UnicodeDecodeError, UnicodeError):
            continue
    else:
        return []

    templates = []
    _st_parse_node(content, 0, [], templates)
    return templates


def _load_templates():
    global TEMPLATES
    TEMPLATES = _builtin_templates()

    # Загрузка пользовательских шаблонов
    tdir = Path(TEMPLATES_DIR)
    if tdir.is_dir():
        for f in tdir.rglob("*.json"):
            try:
                with open(f, "r", encoding="utf-8") as fh:
                    data = json.load(fh)
                if isinstance(data, list):
                    TEMPLATES.extend(data)
                elif isinstance(data, dict) and "templates" in data:
                    TEMPLATES.extend(data["templates"])
            except Exception:
                logger.debug("игнорируем исключение", exc_info=True)
        for f in tdir.rglob("*.bsl"):
            try:
                code = f.read_text(encoding="utf-8-sig")
                # Извлекаем метаданные из комментариев
                title = f.stem
                desc = ""
                tags = []
                for line in code.split("\n")[:10]:
                    line = line.strip()
                    if line.startswith("// Описание:"):
                        desc = line[13:].strip()
                    elif line.startswith("// Теги:"):
                        tags = [t.strip() for t in line[8:].split(",")]
                    elif line.startswith("//") and not title:
                        title = line[2:].strip()
                TEMPLATES.append({
                    "title": title,
                    "description": desc or title,
                    "tags": tags or ["пользовательский"],
                    "code": code,
                })
            except Exception:
                logger.debug("игнорируем исключение", exc_info=True)
        for f in tdir.rglob("*.st"):
            try:
                st_templates = _parse_st_file(str(f))
                TEMPLATES.extend(st_templates)
            except Exception:
                logger.debug("игнорируем исключение", exc_info=True)


